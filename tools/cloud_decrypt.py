#!/usr/bin/env python3
"""
Desktop recovery tool for the Gallery "Cloud sync" encrypted blobs.

Usage:
  python3 cloud_decrypt.py --chat-id -1001234567890 --key "ABCD-EFGH-..." --out restored  blob1.bin blob2.bin ...
  python3 cloud_decrypt.py ... --out restored /path/to/telegram_export/files/*.bin

Works directly on files exported from Telegram Desktop ("Export chat history"), no manifest needed:
every photo blob carries its own (encrypted) header with the original name / mime / date.
Multi-part videos are re-joined automatically. Needs:  pip install cryptography
"""
import argparse
import gzip
import hashlib
import hmac
import json
import os
import re
import struct
import sys
import unicodedata

from cryptography.exceptions import InvalidTag
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

SALT_LEN, NONCE_LEN, TAG_LEN = 16, 12, 16
AAD = b"gcv1"


def normalize(passphrase: str) -> str:
    s = unicodedata.normalize("NFKC", passphrase)
    s = "".join(c for c in s if c not in " \t\n\r-")
    if re.fullmatch(r"[A-Za-z2-7]{32}", s):  # key generated by the app: case-insensitive
        s = s.upper()
    return s


def derive_master(passphrase: str, chat_id: str) -> bytes:
    salt = hashlib.sha256(("gallery-cloud-salt-v1|" + chat_id.strip()).encode()).digest()
    return hashlib.pbkdf2_hmac("sha256", normalize(passphrase).encode(), salt, 600_000, 32)


def hkdf(ikm: bytes, salt: bytes, info: str) -> bytes:
    prk = hmac.new(salt, ikm, hashlib.sha256).digest()
    return hmac.new(prk, info.encode() + b"\x01", hashlib.sha256).digest()


def seal(master: bytes, kind: str, header: bytes, data: bytes) -> bytes:
    salt, nonce = os.urandom(SALT_LEN), os.urandom(NONCE_LEN)
    key = hkdf(master, salt, f"gallery-cloud/{kind}/v1")
    plain_len = 8 + len(header) + len(data)
    padded = max(1, -(-plain_len // 65536)) * 65536
    plain = struct.pack(">II", len(header), len(data)) + header + data
    plain += b"\x00" * (padded - len(plain))
    return salt + nonce + AESGCM(key).encrypt(nonce, plain, AAD)


def open_blob(master: bytes, kind: str, blob: bytes):
    salt, nonce = blob[:SALT_LEN], blob[SALT_LEN:SALT_LEN + NONCE_LEN]
    key = hkdf(master, salt, f"gallery-cloud/{kind}/v1")
    plain = AESGCM(key).decrypt(nonce, blob[SALT_LEN + NONCE_LEN:], AAD)
    hlen, dlen = struct.unpack(">II", plain[:8])
    if 8 + hlen + dlen > len(plain):
        raise ValueError("corrupted container")
    return plain[8:8 + hlen], plain[8 + hlen:8 + hlen + dlen]


def safe_name(name: str, fallback: str) -> str:
    name = "".join(c for c in os.path.basename(name.replace("\\", "/")) if ord(c) >= 32).strip()
    return name[:120] or fallback


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--chat-id", required=True, help="the channel/group id used in the app, e.g. -1001234567890")
    ap.add_argument("--key", required=True, help="recovery key / passphrase set in the app")
    ap.add_argument("--out", default="restored")
    ap.add_argument("files", nargs="+")
    a = ap.parse_args()

    master = derive_master(a.key, a.chat_id)
    os.makedirs(a.out, exist_ok=True)
    parts = {}  # id -> {idx: data, "hdr": header}
    skipped = 0
    for path in a.files:
        try:
            with open(path, "rb") as f:
                hdr_raw, data = open_blob(master, "file", f.read())
            hdr = json.loads(hdr_raw)
        except (InvalidTag, ValueError, json.JSONDecodeError):
            skipped += 1  # manifest blobs, other files, or wrong key
            continue
        entry = parts.setdefault(hdr["id"], {"hdr": hdr, "n": hdr["n"], "data": {}})
        entry["data"][hdr["i"]] = data

    done = 0
    for eid, e in parts.items():
        if len(e["data"]) != e["n"]:
            print(f"incomplete: {e['hdr']['name']} ({len(e['data'])}/{e['n']} parts)")
            continue
        name = safe_name(e["hdr"]["name"], eid)
        target = os.path.join(a.out, name)
        if os.path.exists(target):
            target = os.path.join(a.out, eid[:6] + "_" + name)
        with open(target, "wb") as f:
            for i in range(e["n"]):
                f.write(e["data"][i])
        taken = e["hdr"].get("taken")
        if taken:
            os.utime(target, (taken / 1000, taken / 1000))
        done += 1
    print(f"restored {done} file(s) into {a.out}; skipped {skipped} non-file blob(s)")
    if done == 0 and skipped:
        print("nothing decrypted - check --chat-id and --key", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
