package org.fossify.gallery.cloud

import java.nio.ByteBuffer
import java.security.GeneralSecurityException
import java.security.MessageDigest
import java.security.SecureRandom
import java.text.Normalizer
import javax.crypto.Cipher
import javax.crypto.Mac
import javax.crypto.SecretKeyFactory
import javax.crypto.spec.GCMParameterSpec
import javax.crypto.spec.PBEKeySpec
import javax.crypto.spec.SecretKeySpec

class CloudCryptoException(message: String, cause: Throwable? = null) : Exception(message, cause)

/**
 * Opaque container format for everything that is sent to Telegram.
 *
 * Blob layout (the whole thing looks like random bytes, there is no magic number / header in clear):
 *
 *   salt(16) | nonce(12) | AES-256-GCM( plaintext ) | tag(16)
 *
 *   plaintext = u32be headerLen | u32be dataLen | header(JSON) | data | zero padding
 *               (padded up to a multiple of 64 KiB so the exact file size is hidden)
 *
 * Key hierarchy:
 *   master  = PBKDF2-HMAC-SHA256(passphrase, salt = SHA256("gallery-cloud-salt-v1|" + chatId), 600k iter)
 *   fileKey = HKDF-SHA256(ikm = master, salt = <random 16 bytes stored in the blob>, info = "gallery-cloud/<kind>/v1")
 *
 * So every uploaded blob (every photo, every part of a big video, and every manifest version) is encrypted
 * with its own unique key. The same format is implemented by tools/cloud_decrypt.py for desktop recovery.
 */
object CloudCrypto {
    const val KIND_FILE = "file"
    const val KIND_MANIFEST = "manifest"

    private const val SALT_LEN = 16
    private const val NONCE_LEN = 12
    private const val TAG_LEN = 16
    private const val TAG_BITS = TAG_LEN * 8
    private const val PAD_BLOCK = 64 * 1024
    private const val PBKDF2_ITERATIONS = 600_000
    private const val BASE32 = "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567"
    private val AAD = "gcv1".toByteArray(Charsets.US_ASCII)
    private val random = SecureRandom()

    private val GENERATED_KEY = Regex("^[A-Za-z2-7]{32}$")

    /**
     * Whitespace and dashes are ignored, so "ABCD-EFGH-..." can be typed in any grouping.
     * A recovery key generated by the app (32 base32 chars) is also case-insensitive.
     */
    fun normalizePassphrase(input: String): String {
        val nfkc = Normalizer.normalize(input, Normalizer.Form.NFKC)
        val stripped = nfkc.filter { it != ' ' && it != '\t' && it != '\n' && it != '\r' && it != '-' }
        return if (GENERATED_KEY.matches(stripped)) stripped.uppercase(java.util.Locale.ROOT) else stripped
    }

    fun deriveMasterKey(passphrase: String, chatId: String): ByteArray {
        val salt = MessageDigest.getInstance("SHA-256")
            .digest("gallery-cloud-salt-v1|${chatId.trim()}".toByteArray(Charsets.UTF_8))
        val spec = PBEKeySpec(normalizePassphrase(passphrase).toCharArray(), salt, PBKDF2_ITERATIONS, 256)
        try {
            return SecretKeyFactory.getInstance("PBKDF2WithHmacSHA256").generateSecret(spec).encoded
        } finally {
            spec.clearPassword()
        }
    }

    /** 160 bit random recovery key, e.g. "ABCD-EFGH-...", 8 groups of 4 chars. */
    fun generateRecoveryKey(): String {
        val bytes = ByteArray(20).also { random.nextBytes(it) }
        val sb = StringBuilder()
        var buffer = 0
        var bits = 0
        for (b in bytes) {
            buffer = (buffer shl 8) or (b.toInt() and 0xFF)
            bits += 8
            while (bits >= 5) {
                sb.append(BASE32[(buffer shr (bits - 5)) and 31])
                bits -= 5
            }
            buffer = buffer and ((1 shl bits) - 1)
        }
        return sb.toString().chunked(4).joinToString("-")
    }

    fun randomId(): String = ByteArray(16).also { random.nextBytes(it) }.toHex()

    /** Name used for the document in Telegram: random, no extension that hints at the content. */
    fun randomUploadName(): String = ByteArray(10).also { random.nextBytes(it) }.toHex() + ".bin"

    private fun hkdf(ikm: ByteArray, salt: ByteArray, info: String): ByteArray {
        val mac = Mac.getInstance("HmacSHA256")
        mac.init(SecretKeySpec(salt, "HmacSHA256"))
        val prk = mac.doFinal(ikm)
        mac.init(SecretKeySpec(prk, "HmacSHA256"))
        mac.update(info.toByteArray(Charsets.US_ASCII))
        mac.update(1.toByte())
        return mac.doFinal() // 32 bytes, exactly one HKDF block
    }

    fun seal(
        master: ByteArray,
        kind: String,
        header: ByteArray,
        data: ByteArray,
        dataOffset: Int = 0,
        dataLength: Int = data.size
    ): ByteArray {
        val salt = ByteArray(SALT_LEN).also { random.nextBytes(it) }
        val nonce = ByteArray(NONCE_LEN).also { random.nextBytes(it) }
        val key = hkdf(master, salt, "gallery-cloud/$kind/v1")

        val plainLen = 8 + header.size + dataLength
        val paddedLen = ((plainLen + PAD_BLOCK - 1) / PAD_BLOCK).coerceAtLeast(1) * PAD_BLOCK
        val plain = ByteBuffer.allocate(paddedLen)
            .putInt(header.size)
            .putInt(dataLength)
            .put(header)
            .put(data, dataOffset, dataLength)
            .array()

        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        cipher.init(Cipher.ENCRYPT_MODE, SecretKeySpec(key, "AES"), GCMParameterSpec(TAG_BITS, nonce))
        cipher.updateAAD(AAD)

        val out = ByteArray(SALT_LEN + NONCE_LEN + paddedLen + TAG_LEN)
        System.arraycopy(salt, 0, out, 0, SALT_LEN)
        System.arraycopy(nonce, 0, out, SALT_LEN, NONCE_LEN)
        cipher.doFinal(plain, 0, plain.size, out, SALT_LEN + NONCE_LEN)
        plain.fill(0)
        key.fill(0)
        return out
    }

    class Opened(val header: ByteArray, val data: ByteArray)

    fun open(master: ByteArray, kind: String, blob: ByteArray): Opened {
        if (blob.size < SALT_LEN + NONCE_LEN + TAG_LEN + 8) {
            throw CloudCryptoException("Blob too small")
        }
        val salt = blob.copyOfRange(0, SALT_LEN)
        val nonce = blob.copyOfRange(SALT_LEN, SALT_LEN + NONCE_LEN)
        val key = hkdf(master, salt, "gallery-cloud/$kind/v1")
        val plain: ByteArray
        try {
            val cipher = Cipher.getInstance("AES/GCM/NoPadding")
            cipher.init(Cipher.DECRYPT_MODE, SecretKeySpec(key, "AES"), GCMParameterSpec(TAG_BITS, nonce))
            cipher.updateAAD(AAD)
            plain = cipher.doFinal(blob, SALT_LEN + NONCE_LEN, blob.size - SALT_LEN - NONCE_LEN)
        } catch (e: GeneralSecurityException) {
            throw CloudCryptoException("Wrong key or corrupted data", e)
        } finally {
            key.fill(0)
        }

        val buf = ByteBuffer.wrap(plain)
        val headerLen = buf.int
        val dataLen = buf.int
        if (headerLen < 0 || dataLen < 0 || 8L + headerLen + dataLen > plain.size) {
            throw CloudCryptoException("Corrupted container")
        }
        val header = plain.copyOfRange(8, 8 + headerLen)
        val data = plain.copyOfRange(8 + headerLen, 8 + headerLen + dataLen)
        plain.fill(0)
        return Opened(header, data)
    }
}

fun ByteArray.toHex(): String {
    val sb = StringBuilder(size * 2)
    for (b in this) {
        sb.append("0123456789abcdef"[(b.toInt() shr 4) and 0xF])
        sb.append("0123456789abcdef"[b.toInt() and 0xF])
    }
    return sb.toString()
}
